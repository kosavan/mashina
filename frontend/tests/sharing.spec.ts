import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";

test("local accounts, driver UI and revoked offline drafts remain isolated", async ({ page, context, request }) => {
  const credentials = { username: "browser-owner", password: "browser-test-password", bootstrap_token: "browser-test-bootstrap-only" };
  const setup = await request.get("/api/v1/setup");
  const login = await request.post((await setup.json()).required ? "/api/v1/setup" : "/api/v1/login", { data: credentials });
  expect(login.ok()).toBeTruthy();
  const owner = await login.json();
  const headers = { "X-CSRF-Token": owner.csrf };
  async function mutate(entity: string, data: object) {
    const response = await request.post("/api/v1/mutate", { headers, data: { operation_id: randomUUID(), id: randomUUID(), entity, action: "create", data } });
    expect(response.ok()).toBeTruthy(); return (await response.json()).record;
  }
  const name = "driver-"+randomUUID().slice(0,8);
  const created = await request.post("/api/v1/users", { headers, data: { username: name, password: "browser-driver-password" } });
  expect(created.ok()).toBeTruthy();
  const driver = await created.json();
  const car = await mutate("vehicle", { name: "Совместный автомобиль" });
  await mutate("vehicle", { name: "Личный автомобиль владельца" });
  await mutate("event", { vehicle_id: car.id, kind: "expense", amount: "100", description: "Запись владельца", occurred_at: "2026-10-01" });
  expect((await request.put(`/api/v1/vehicles/${car.id}/access/${driver.id}`, { headers, data: { role: "driver" } })).ok()).toBeTruthy();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByLabel("Имя пользователя", { exact: true }).fill(name);
  await page.getByLabel("Пароль", { exact: true }).fill("browser-driver-password");
  await page.getByRole("button", { name: "Войти в гараж", exact: true }).click();
  await expect(page.getByRole("heading", { name: car.name, exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Личный автомобиль владельца", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Редактировать Совместный автомобиль", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Редактировать Запись владельца", exact: true })).toHaveCount(0);
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await expect(page.getByRole("heading", { name: car.name, exact: true })).toBeVisible();
  await context.setOffline(true);
  await page.getByRole("button", { name: "Добавить запись", exact: true }).click();
  await page.getByRole("button", { name: "Расход Любая покупка для автомобиля" }).click();
  await page.getByLabel("Сумма, ₽", { exact: true }).fill("222.22");
  await page.getByLabel("Описание", { exact: true }).fill("Черновик после отзыва");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  expect((await request.delete(`/api/v1/vehicles/${car.id}/access/${driver.id}`, { headers })).ok()).toBeTruthy();
  await context.setOffline(false);
  await expect(page.getByRole("heading", { name: car.name, exact: true })).toHaveCount(0);
  await expect(page.locator(".event-row").getByText("Черновик после отзыва", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Скачать черновик", exact: true })).toBeVisible();
  await expect.poll(async () => page.evaluate(async () => {
    return new Promise<number>((resolve, reject) => { const req = indexedDB.open("mashina-private-v1", 1); req.onsuccess = () => { const rows = req.result.transaction("outbox").objectStore("outbox").getAll(); rows.onsuccess = () => resolve(rows.result[0]?.status || 0); rows.onerror = () => reject(rows.error); }; });
  })).toBe(403);
  const server = await request.get("/api/v1/state");
  expect((await server.json()).events.some((e: any) => e.description === "Черновик после отзыва")).toBe(false);
  await page.screenshot({ path: "../.cache/screenshots/sharing-revoked-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator(".sidebar").getByRole("button", { name: "Настройки", exact: true }).click();
  await expect(page.getByRole("button", { name: "Скачать полный архив", exact: true })).toHaveCount(0);
  page.once("dialog", d => d.accept());
  await page.getByRole("button", { name: "Выйти из гаража", exact: true }).click();
  await page.getByLabel("Имя пользователя", { exact: true }).fill("browser-owner");
  await page.getByLabel("Пароль", { exact: true }).fill("browser-test-password");
  await page.getByRole("button", { name: "Войти в гараж", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Личный автомобиль владельца", exact: true }).first()).toBeVisible();
  await page.locator(".sidebar").getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByRole("button", { name: "Выйти из гаража", exact: true }).click();
  await page.getByLabel("Имя пользователя", { exact: true }).fill(name);
  await page.getByLabel("Пароль", { exact: true }).fill("browser-driver-password");
  await page.getByRole("button", { name: "Войти в гараж", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Мой гараж", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Личный автомобиль владельца", exact: true })).toHaveCount(0);
});

test("owner can create an account and grant access through polished sheets", async ({ page, request }) => {
  const logged = await request.post("/api/v1/login", { data: { username: "browser-owner", password: "browser-test-password" } });
  const owner = await logged.json();
  const carResponse = await request.post("/api/v1/mutate", { headers: { "X-CSRF-Token": owner.csrf }, data: { operation_id: randomUUID(), id: randomUUID(), entity: "vehicle", action: "create", data: { name: "Доступ через интерфейс" } } });
  expect(carResponse.ok()).toBeTruthy();
  const car = (await carResponse.json()).record;
  await page.goto("/");
  await page.getByLabel("Имя пользователя", { exact: true }).fill("browser-owner");
  await page.getByLabel("Пароль", { exact: true }).fill("browser-test-password");
  await page.getByRole("button", { name: "Войти в гараж", exact: true }).click();
  await page.locator(".sidebar").getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByRole("button", { name: "Пользователи", exact: true }).click();
  const name = "ui-driver-"+randomUUID().slice(0,8);
  await page.getByRole("dialog").getByLabel("Имя пользователя", { exact: true }).fill(name);
  await page.getByLabel("Новый пароль", { exact: false }).fill("browser-driver-password");
  await page.getByRole("button", { name: "Создать аккаунт", exact: true }).click();
  await expect(page.getByRole("dialog").getByText(name, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await page.locator(".sidebar").getByRole("button", { name: "Мой гараж", exact: true }).click();
  await page.getByRole("heading", { name: car.name, exact: true }).last().click();
  await page.getByRole("button", { name: "Доступ", exact: true }).click();
  await page.getByRole("combobox", { name: "Пользователь", exact: true }).selectOption({ label: name });
  await page.getByRole("button", { name: "Предоставить доступ", exact: true }).click();
  await expect(page.getByRole("dialog").getByText(name, { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "../.cache/screenshots/sharing-owner-mobile.png", fullPage: true });
  const state = await request.get(`/api/v1/vehicles/${car.id}/access`);
  expect((await state.json()).members.some((m: any) => m.username === name)).toBe(true);
});
